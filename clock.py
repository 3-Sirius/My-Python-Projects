import turtle
p = turtle.Turtle()
p.color("blue")
p.pensize(5)
p.circle(120)
p.penup()
p.goto(0,20)
for i in range(12):
    p.dot(10,"blue")
    p.circle(100,30)
p.goto(0,120)
p.pendown()
p.color("black")
p.pensize(2)
p.goto(0,200)
p.penup()
p.goto(0,120)
p.pendown()
p.pensize(3)
p.goto(40,120)
p.penup()
p.goto(0,120)
p.dot(15,"red")
p.hideturtle()